import assert from 'node:assert/strict'
const base = process.env.TEST_BASE_URL || 'http://localhost:3000'
const catalogue = await fetch(`${base}/api/products`)
assert.equal(catalogue.status, 200)
const products = await catalogue.json()
assert.ok(products.length > 0, 'Seed products before running smoke checks')
const home = await (await fetch(base)).text()
assert.match(home, /<title>Everyday Jewellery, Extraordinary You \| Nuvana Glitter<\/title>/)
assert.match(home, /property="og:description"/)
assert.match(home, /rel="canonical"/)
assert.match(home, /srcset=/)
for (const product of products) {
  const response = await fetch(`${base}/products/${product.slug}`)
  assert.equal(response.status, 200)
  const html = await response.text()
  assert.ok(html.includes(`<title>${product.name} | Nuvana Glitter</title>`))
  const schema = JSON.parse(html.match(/<script type="application\/ld\+json">(.*?)<\/script>/s)[1])
  assert.equal(schema['@type'], 'Product')
  assert.equal(schema.offers.price, product.price)
  assert.equal(schema.offers.priceCurrency, 'KES')
}
const cart = await (await fetch(`${base}/cart`)).text()
assert.match(cart, /noindex, follow/)
const sitemap = await (await fetch(`${base}/sitemap.xml`)).text()
for (const product of products) assert.ok(sitemap.includes(`/products/${product.slug}`))
assert.ok(!sitemap.includes('/cart'))
assert.match(await (await fetch(`${base}/robots.txt`)).text(), /Sitemap:/)
assert.equal((await fetch(`${base}/api/products/does-not-exist`)).status, 404)
assert.equal((await fetch(`${base}/products/does-not-exist`)).status, 404)
console.log(`Passed: catalogue, ${products.length} SSR product pages and schemas, canonical/Open Graph, cart noindex, sitemap, robots, image srcsets and 404s.`)
